"""Solar-array power generation, eclipse illumination and the power monitor.

Inventory items **P1** (solar array) and **P2** (eclipse).  Configured in
:mod:`adcs_sim.config.power`.

Power only -- never dynamics
----------------------------
Each panel reads the spacecraft state and the Sun ephemeris and writes a power
message.  Nothing here is a dynamic effector, nothing subscribes to an actuator
command, and no power value reaches the flight software: the DLL's input struct
has no power port.  The models are registered *after* the controller, so the
control loop sees exactly the same measurements it saw before the array
existed.

What ``SimpleSolarPanel`` computes
----------------------------------
Measured on Basilisk 2.11.1 (see ``config/power.SOLAR_CONSTANT_1AU_W_M2``):

.. code-block:: text

    netPower = 1361 W/m^2 * (AU / |r_sun - r_sc|)^2
               * area * efficiency * max(0, cos(theta)) * illuminationFactor

with ``theta`` the angle between the panel normal in inertial space and the
direction to the Sun.  The cosine is clamped at zero, so a panel facing away
generates nothing rather than a negative power.  The sunlit fraction comes from
the eclipse module -- 1 in full sun, 0 in umbra, fractional in penumbra; see
:func:`sunlit_fraction` for what this build calls that field.  Without an
eclipse input a panel assumes full sunlight.
"""

from dataclasses import dataclass, field

import numpy as np
from Basilisk.simulation import (eclipse, simplePowerMonitor, simplePowerSink,
                                 simpleSolarPanel)

from adcs_sim.config import power as power_cfg


@dataclass
class SolarArray:
    """The power models, and the live readouts taken from their messages."""

    #: One ``SimpleSolarPanel`` per entry in ``config.power.SOLAR_PANELS``.
    panels: list
    #: Matching :class:`~adcs_sim.config.power.SolarPanel` configuration.
    panel_config: tuple
    #: ``Eclipse`` model, or ``None`` when eclipse is disabled.
    eclipse: object = None
    #: ``SimplePowerMonitor`` accumulating generated (or net) energy.
    monitor: object = None
    #: ``SimplePowerSink`` for the housekeeping load, or ``None``.
    bus_load: object = None
    #: Anything else that must not be garbage-collected mid-run.
    retained: list = field(default_factory=list)

    # -- live readouts -----------------------------------------------------
    # Each reads the module's own output message, so they are valid at any
    # point after a step and cost nothing when nobody calls them.

    def panel_powers_w(self):
        """Power generated by each panel this step [W]."""
        return [float(panel.nodePowerOutMsg.read().netPower)
                for panel in self.panels]

    def total_power_w(self):
        """Power generated by the whole array this step [W]."""
        return float(sum(self.panel_powers_w()))

    def net_power_w(self):
        """Array generation minus the housekeeping load [W]."""
        if self.monitor is None:
            return self.total_power_w()
        return float(self.monitor.batPowerOutMsg.read().currentNetPower)

    def energy_wh(self):
        """Energy accumulated by the monitor since t = 0 [W h]."""
        if self.monitor is None:
            return 0.0
        return float(self.monitor.batPowerOutMsg.read().storageLevel) / 3600.0

    def illumination_factor(self):
        """Sunlight fraction: 1 in full sun, 0 in umbra, 1 with no eclipse."""
        if self.eclipse is None:
            return 1.0
        return float(sunlit_fraction(self.eclipse.eclipseOutMsgs[0].read()))

    @property
    def peak_power_w(self):
        """Power at normal incidence, 1 AU, full sun -- the plot's ceiling [W].

        Computed per panel and summed, which is the right ceiling for panels
        that can be lit at once and a deliberately unreachable one for the
        back-to-back wing pair, where only one side ever generates.
        """
        return sum(power_cfg.SOLAR_CONSTANT_1AU_W_M2 * panel.area_m2
                   * panel.efficiency for panel in self.panel_config)


def sunlit_fraction(source):
    """Return the eclipse sunlit fraction, whatever this build names the field.

    Basilisk 2.11.1 is mid-rename and the two names are not interchangeable in
    practice: a payload read back from an ``Eclipse`` output message carries
    only ``shadowFactor``, while a freshly constructed ``EclipseMsgPayload``
    also answers to ``illuminationFactor``.  Both hold the same number -- 1 in
    full sun, 0 in umbra -- so take whichever the object has.  Works on a
    recorder too, where the attribute is the recorded history rather than one
    sample.
    """
    value = getattr(source, "illuminationFactor", None)
    return source.shadowFactor if value is None else value


def _unit(vector):
    """Return ``vector`` normalised; panel normals may be given as plain axes."""
    vector = np.asarray(vector, dtype=float)
    return vector / np.linalg.norm(vector)


def add_solar_array(sim, task_name, hub_spacecraft, planet_state_msgs):
    """Create the eclipse model, the panels and the monitor, and register them.

    Parameters
    ----------
    planet_state_msgs : dict
        Occulting-body name -> SPICE planet state message, for the eclipse
        model.  Ignored when ``POWER_ECLIPSE_ENABLED`` is False.

    Returns
    -------
    SolarArray or None
        ``None`` when ``POWER_MODEL_ENABLED`` is False.

    Notes
    -----
    Message subscriptions are made by :func:`connect_solar_array`, in keeping
    with the rest of the package: construction here, wiring in
    ``builder.connect_messages``.  The eclipse model's spacecraft and planet
    *registrations* are not subscriptions -- they build the model's internal
    lists and must happen at construction.
    """
    if not power_cfg.POWER_MODEL_ENABLED:
        return None

    shadow = None
    if power_cfg.POWER_ECLIPSE_ENABLED:
        shadow = eclipse.Eclipse()
        shadow.ModelTag = power_cfg.ECLIPSE_MODEL_TAG
        # Order matters only in that eclipseOutMsgs[i] follows the order
        # spacecraft were added; there is one spacecraft here.
        shadow.addSpacecraftToModel(hub_spacecraft.scStateOutMsg)
        for body in power_cfg.ECLIPSE_OCCULTING_BODIES:
            shadow.addPlanetToModel(planet_state_msgs[body])
        sim.AddModelToTask(task_name, shadow)

    panels = []
    for index, config in enumerate(power_cfg.SOLAR_PANELS):
        panel = simpleSolarPanel.SimpleSolarPanel()
        panel.ModelTag = f"{power_cfg.SOLAR_PANEL_MODEL_TAG_PREFIX}_{index}"
        panel.setPanelParameters(_unit(config.normal_B), config.area_m2,
                                 config.efficiency)
        sim.AddModelToTask(task_name, panel)
        panels.append(panel)

    bus_load = None
    if power_cfg.BUS_LOAD_W > 0.0:
        bus_load = simplePowerSink.SimplePowerSink()
        bus_load.ModelTag = power_cfg.POWER_SINK_MODEL_TAG
        # A sink is a negative power node, which is how it is subtracted from
        # generation inside the monitor.
        bus_load.nodePowerOut = -power_cfg.BUS_LOAD_W
        sim.AddModelToTask(task_name, bus_load)

    monitor = simplePowerMonitor.SimplePowerMonitor()
    monitor.ModelTag = power_cfg.POWER_MONITOR_MODEL_TAG
    monitor.storedCharge_Init = power_cfg.INITIAL_STORED_ENERGY_WS
    for panel in panels:
        monitor.addPowerNodeToModel(panel.nodePowerOutMsg)
    if bus_load is not None:
        monitor.addPowerNodeToModel(bus_load.nodePowerOutMsg)
    sim.AddModelToTask(task_name, monitor)

    return SolarArray(panels=panels, panel_config=power_cfg.SOLAR_PANELS,
                      eclipse=shadow, monitor=monitor, bus_load=bus_load)


def connect_solar_array(array, sun_state_msg, sc_state_msg):
    """Subscribe the panels to the Sun, the spacecraft state and the eclipse."""
    if array is None:
        return

    if array.eclipse is not None:
        array.eclipse.sunInMsg.subscribeTo(sun_state_msg)

    for panel in array.panels:
        panel.sunInMsg.subscribeTo(sun_state_msg)
        panel.stateInMsg.subscribeTo(sc_state_msg)
        if array.eclipse is not None:
            panel.sunEclipseInMsg.subscribeTo(array.eclipse.eclipseOutMsgs[0])


def describe(array):
    """Return printable lines describing the array, if there is one."""
    if array is None:
        return ["Solar array: none (power model disabled)"]

    total_area = sum(panel.area_m2 for panel in array.panel_config)
    lines = [
        f"Solar array: {len(array.panel_config)} panels, "
        f"{total_area:g} m^2 total, "
        f"peak {array.peak_power_w:.0f} W at normal incidence",
    ]
    for panel in array.panel_config:
        normal = _unit(panel.normal_B)
        lines.append(
            f"  {panel.name}: n_B = [{normal[0]:+.2f} {normal[1]:+.2f} "
            f"{normal[2]:+.2f}], {panel.area_m2:g} m^2, "
            f"eff {panel.efficiency:.0%}")
    lines.append(f"  eclipse: "
                 f"{'Earth shadow modelled' if array.eclipse is not None else 'OFF (always full sun)'}")
    load = ("none -- monitor reports generation only"
            if array.bus_load is None
            else f"{power_cfg.BUS_LOAD_W:g} W constant")
    lines.append(f"  housekeeping load: {load}")
    return lines
