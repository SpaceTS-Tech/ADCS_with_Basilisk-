<#
.SYNOPSIS
    Build ADCS_Software_v1.dll for the Basilisk scenario.

.DESCRIPTION
    ADCS_Software_v1.mk, generated by Simulink Coder, builds the standalone
    ADCS_Software_v1.exe.  It has no target that links adcs_basilisk_wrapper.c
    into a shared library, so the DLL the Python scenario loads was previously
    produced by an ad-hoc command that lived nowhere.

    On 2026-08-03 that let the DLL drift one revision behind the Simulink model
    (2.23 vs 2.24) with nothing to report it.  The difference sat exactly in the
    OPTICAL control law -- the built model damped the two image axes at 0.1 *
    kd_point -- so mission command 9 misbehaved in Basilisk while the model
    tested correctly in MATLAB.

    Run this after every regeneration.  By default it re-syncs the generated
    sources from the Simulink codegen folder first, so the binary cannot
    silently lag behind the model again.

.PARAMETER NoSync
    Build from the sources already in this folder instead of copying fresh ones
    from CodegenDir.  Use on a machine without the Simulink codegen tree.

.PARAMETER CodegenDir
    Where Simulink Coder writes the generated code.  If the default folder does
    not exist, the sources already in this folder are used, provided they are
    not older than ModelFile.

.PARAMETER ModelFile
    The Simulink model, used to detect stale generated code when building from
    the local sources.

.PARAMETER StarTrackerDir
    Folder holding st_simulink.h and st_startracker_all.c, the star tracker the
    model's '<Root>/STR 1' C Function block calls.  Only used when the
    generated header includes st_simulink.h.

.EXAMPLE
    .\build_dll.ps1
    .\build_dll.ps1 -NoSync
#>
[CmdletBinding()]
param(
    [switch]$NoSync,
    [string]$CodegenDir,
    [string]$ModelFile,
    [string]$StarTrackerDir,
    [string]$MingwRoot = $(if ($env:MINGW_ROOT) { $env:MINGW_ROOT } else { 'C:\mingw64\bin' }),
    [string]$MatlabRoot = $(if ($env:MATLAB_ROOT) { $env:MATLAB_ROOT } else { 'C:\Program Files\MATLAB\R2026a' })
)

$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot

$codegenDirGiven = [bool]$CodegenDir
if (-not $CodegenDir) {
    $CodegenDir = Join-Path $here '..\..\FlightSW_testing\ADCS_Software_v1_grt_rtw'
}
if (-not $ModelFile) {
    $ModelFile = Join-Path $here '..\..\FlightSW_testing\ADCS_Software_v1.slx'
}
if (-not $StarTrackerDir) {
    $StarTrackerDir = Join-Path $here '..\..\..\Star Trcaker\startracker_c\matlab'
}

$gcc = Join-Path $MingwRoot 'gcc.exe'
if (-not (Test-Path $gcc)) {
    throw "gcc not found at '$gcc'. Set -MingwRoot (or `$env:MINGW_ROOT) to your MinGW-W64 bin directory."
}

# gcc only DRIVES the compile; the real work happens in libexec/.../cc1.exe,
# which links against libgmp / libmpfr / libmpc / libisl / libwinpthread in
# this same bin directory.  Invoking gcc by absolute path without that
# directory on PATH lets gcc start but leaves cc1 unable to load its DLLs: it
# dies with STATUS_DLL_NOT_FOUND (0xC0000135) *before printing anything*, so
# the build fails with an empty error and a bare non-zero exit code.
$env:PATH = "$MingwRoot;$env:PATH"
$rtLogging = Join-Path $MatlabRoot 'rtw\c\src\rt_logging.c'
if (-not (Test-Path $rtLogging)) {
    throw "MATLAB not found at '$MatlabRoot'. Set -MatlabRoot (or `$env:MATLAB_ROOT)."
}

# ---------------------------------------------------------------------------
# 1. Sync the generated sources
# ---------------------------------------------------------------------------
# Only Simulink-generated files are copied.  adcs_basilisk_wrapper.c is hand
# written and lives here.  The .mk / .rsp / .mat files are deliberately left
# alone: they carry absolute paths into the codegen tree and this build does
# not use them.
$generated = @(
    'ADCS_Software_v1.c'
    'ADCS_Software_v1.h'
    'ADCS_Software_v1_data.c'
    'ADCS_Software_v1_private.h'
    'ADCS_Software_v1_types.h'
    'builtin_typeid_types.h'
    'multiword_types.h'
    'rt_nonfinite.c'
    'rt_nonfinite.h'
    'rtmodel.h'
    'rtwtypes.h'
)

# Simulink Coder creates <model>_grt_rtw in MATLAB's *current folder*, so when
# code is generated with this folder's parent as the current folder it lands
# here directly and there is nothing to sync.  Only the default CodegenDir
# falls back to that; an explicit -CodegenDir that is missing is still an error.
$localSources = $false
if ($NoSync) {
    Write-Host 'Skipping source sync (-NoSync).'
    $localSources = $true
} elseif (-not (Test-Path (Join-Path $CodegenDir 'ADCS_Software_v1.c'))) {
    if ($codegenDirGiven) {
        throw "No generated code at '$CodegenDir'. Pass -CodegenDir, or -NoSync to build from the local copies."
    }
    Write-Host "No generated code at the default '$CodegenDir';"
    Write-Host 'building from the sources Simulink generated in this folder.'
    $localSources = $true
} elseif ((Resolve-Path $CodegenDir).Path -eq (Resolve-Path $here).Path) {
    Write-Host 'CodegenDir is this folder; nothing to sync.'
    $localSources = $true
} else {
    Write-Host "Syncing generated sources from $((Resolve-Path $CodegenDir).Path)"
    foreach ($file in $generated) {
        Copy-Item (Join-Path $CodegenDir $file) (Join-Path $here $file) -Force
    }
}

# Without a sync, nothing ties the local sources to the model, so check that the
# model was not saved after the code was generated.  -NoSync skips this too:
# it is the explicit "I know these are the sources I want" switch.
if ($localSources -and -not $NoSync) {
    $localCode = Get-Item (Join-Path $here 'ADCS_Software_v1.c')
    if (Test-Path $ModelFile) {
        $model = Get-Item $ModelFile
        if ($model.LastWriteTime -gt $localCode.LastWriteTime) {
            throw ("'$($model.FullName)' ($($model.LastWriteTime)) is newer than the generated " +
                   "code ($($localCode.LastWriteTime)). Regenerate the code, or pass -NoSync " +
                   "to build the existing sources anyway.")
        }
    } else {
        Write-Warning "Model '$ModelFile' not found; cannot check the sources are current. Pass -ModelFile."
    }
}

$version = (Select-String -Path (Join-Path $here 'ADCS_Software_v1.h') `
                          -Pattern 'Model version' | Select-Object -First 1).Line.Trim()
Write-Host "Building from: $version"

# ---------------------------------------------------------------------------
# 2. Compile
# ---------------------------------------------------------------------------
# Flags mirror ADCS_Software_v1.mk (CFLAGS / DEFINES / INCLUDES).  MAT_FILE=1 is
# what pulls in rt_logging.c, which ADCS_Software_v1.c calls.
$cflags = @(
    '-c', '-m64', '-O0', '-msse2', '-fno-predictive-commoning',
    '-Wno-error=incompatible-pointer-types', '-Wno-error=stringop-overflow'
)
$defines = @(
    '-DCLASSIC_INTERFACE=0', '-DALLOCATIONFCN=0', '-DMAT_FILE=1', '-DONESTEPFCN=1',
    '-DTERMFCN=1', '-DMULTI_INSTANCE_CODE=0', '-DINTEGER_CODE=0', '-DMT=0',
    '-DTID01EQ=0', '-DMODEL=ADCS_Software_v1', '-DNUMST=1', '-DNCSTATES=0',
    '-DHAVESTDIO', '-DRT', '-DUSE_RTMODEL'
)
$includes = @(
    "-I$here"
    "-I$(Join-Path $MatlabRoot 'extern\include')"
    "-I$(Join-Path $MatlabRoot 'simulink\include')"
    "-I$(Join-Path $MatlabRoot 'rtw\c\src')"
    "-I$(Join-Path $MatlabRoot 'rtw\c\src\ext_mode\common')"
)

$objDir = Join-Path $here 'dllobj'
if (-not (Test-Path $objDir)) { New-Item -ItemType Directory $objDir | Out-Null }

$sources = [ordered]@{
    'ADCS_Software_v1'      = Join-Path $here 'ADCS_Software_v1.c'
    'ADCS_Software_v1_data' = Join-Path $here 'ADCS_Software_v1_data.c'
    'rt_nonfinite'          = Join-Path $here 'rt_nonfinite.c'
    'adcs_basilisk_wrapper' = Join-Path $here 'adcs_basilisk_wrapper.c'
    'rt_logging'            = $rtLogging
}

# Model 2.128 added a C Function block that calls the star tracker.  Its source
# is external to the generated code (the .mk lists it by absolute path), so it
# is compiled from StarTrackerDir rather than synced.
if (Select-String -Path (Join-Path $here 'ADCS_Software_v1.h') -Pattern 'st_simulink\.h' -Quiet) {
    $stSource = Join-Path $StarTrackerDir 'st_startracker_all.c'
    if (-not (Test-Path $stSource)) {
        throw "The model calls the star tracker, but '$stSource' was not found. Set -StarTrackerDir."
    }
    $StarTrackerDir = (Resolve-Path $StarTrackerDir).Path
    Write-Host "Star tracker from $StarTrackerDir"
    $includes += "-I$StarTrackerDir"
    $sources['st_startracker_all'] = Join-Path $StarTrackerDir 'st_startracker_all.c'
}

Write-Host 'Compiling...'
$objects = @()
foreach ($name in $sources.Keys) {
    $obj = Join-Path $objDir "$name.o"
    & $gcc @cflags @defines @includes $sources[$name] -o $obj
    if ($LASTEXITCODE -ne 0) { throw "Compile failed for $($sources[$name])" }
    $objects += $obj
}

# ---------------------------------------------------------------------------
# 3. Link
# ---------------------------------------------------------------------------
# --export-all-symbols is REQUIRED, not cosmetic.  The Python side reads and
# writes the control gains (kp_point, kd_point, I_RW, ...) as exported DATA
# symbols through ctypes.c_double.in_dll, and mirrors ADCS_Software_v1_U / _Y /
# _B directly.  Without it MinGW exports functions only, and every gain lookup
# raises "not an exported symbol".
$dll = Join-Path $here 'ADCS_Software_v1.dll'
$lib = Join-Path $here 'ADCS_Software_v1.lib'

Write-Host 'Linking...'
& $gcc '-shared' '-m64' '-static-libgcc' @objects `
    '-o' $dll `
    '-Wl,--export-all-symbols' `
    "-Wl,--out-implib,$lib"
if ($LASTEXITCODE -ne 0) {
    throw ("Link failed. If the message mentions a locked or busy file, a Python " +
           "process still has the DLL mapped -- close it and re-run.")
}

Write-Host ''
Write-Host "Built $dll"
Write-Host ("       {0:N0} bytes, {1}" -f (Get-Item $dll).Length, (Get-Item $dll).LastWriteTime)
